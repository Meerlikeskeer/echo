#!/usr/bin/env node
// Generates tasks/INDEX.md from tasks/<TASK-ID>.md, and fails when the
// committed index does not match.
//
// ENG-019, and it replaces scripts/status-table.mjs. ENG-014 already learned
// this lesson once and only applied it halfway. It split STATUS.md's *In flight*
// section into one file per task, because a shared section that every branch
// edits is a conflict generator — but it left every task's *record* in one
// 1,100-line TASKS.md, and left the generated table inside STATUS.md. So two
// branches still collided on both files, every single time, which is exactly
// what happened to WEB-015, WEB-007, ENG-016 and ENG-018.
//
// The rule, stated once: **no file that every task must edit.** A task record is
// a file. The index is generated. The index lives in its own file rather than
// inside STATUS.md so that `.gitattributes` can give it `merge=union`, which
// makes two branches adding two rows resolve themselves instead of conflicting.
// A union merge can leave the rows out of order or duplicated, and `--check`
// catches that; `npm run tasks:build` fixes it.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import path from "node:path";

const DIRECTORY = "tasks";
const INDEX = path.join(DIRECTORY, "INDEX.md");

// A task file looks like:
//   ## ENG-010 — Reproducible hosted deployment and deployed-origin verification
//   **Status:** Done and verified · **Branch:** `eng/ENG-010-...` · **Dependencies:** ...
// Every field after Status is optional, and Status runs to the first `·`.
const HEADING = /^## ([A-Z]{3}-\d{3}) — (.+)$/;
const STATUS_LINE = /^\*\*Status:\*\*\s*(.+)$/;
const FILENAME = /^([A-Z]{3}-\d{3})\.md$/;

// Markdown emphasis is stripped rather than preserved: the cell is truncated,
// and truncating inside `**bold**` leaves an unbalanced marker that corrupts the
// rest of the row. The full text is one click away in the task's own file.
function toCell(text, limit) {
  let cell = text.replace(/\*\*/g, "").replace(/\|/g, "\\|").trim();
  if (cell.length > limit) {
    const cut = cell.slice(0, limit);
    const boundary = cut.lastIndexOf(" ");
    cell = `${(boundary > limit / 2 ? cut.slice(0, boundary) : cut).trimEnd()}…`;
  }
  // A backtick left unclosed by truncation would swallow the rest of the table.
  if ((cell.match(/`/g) ?? []).length % 2 === 1) cell = cell.replace(/`([^`]*)$/, "$1");
  return cell;
}

function readTask(file) {
  const id = FILENAME.exec(file)?.[1];
  if (!id) return null;
  const source = readFileSync(path.join(DIRECTORY, file), "utf8");
  const task = { id, title: "", status: "Todo", branch: "" };
  let seenStatus = false;
  for (const line of source.split("\n")) {
    const heading = HEADING.exec(line);
    if (heading) {
      if (heading[1] !== id) {
        console.error(`tasks: ${file} declares ${heading[1]}. A task file's name must match its heading.`);
        process.exit(2);
      }
      task.title = heading[2];
      continue;
    }
    if (seenStatus) continue;
    const status = STATUS_LINE.exec(line);
    if (!status) continue;
    seenStatus = true;
    const fields = status[1].split("·");
    task.status = fields[0];
    const branch = fields.find((field) => field.includes("**Branch:**"));
    // The first backticked token is the branch; anything after it is a base
    // commit or a parenthetical, which belongs in the task file, not a table.
    task.branch = branch ? (/`([^`]+)`/.exec(branch)?.[1] ?? "") : "";
  }
  if (!task.title) {
    console.error(`tasks: ${file} has no "## ${id} — Title" heading.`);
    process.exit(2);
  }
  return task;
}

// Sorted, not hand-ordered. A hand-kept order is one more thing every task must
// edit, which is the problem this script exists to remove. Sorting by prefix
// then number is stable, so two branches adding two tasks produce the same file
// whichever merges first.
const RANK = { DOC: 0, ENG: 1, INT: 2, WEB: 3 };
function compare(a, b) {
  const rank = (RANK[a.id.slice(0, 3)] ?? 9) - (RANK[b.id.slice(0, 3)] ?? 9);
  return rank || Number(a.id.slice(4)) - Number(b.id.slice(4));
}

const tasks = readdirSync(DIRECTORY)
  .filter((file) => FILENAME.test(file))
  .map(readTask)
  .filter(Boolean)
  .sort(compare);

if (tasks.length === 0) {
  console.error(`tasks: no task files found in ${DIRECTORY}/. Expected names like ENG-010.md.`);
  process.exit(2);
}

const rendered = [
  "# Task index",
  "",
  "**Generated by `npm run tasks:build` from the files beside it. Do not edit this by hand.**",
  "Each task's record — scope, decisions, handoff, the commands that were actually run — is in its own",
  "`tasks/<TASK-ID>.md`. That file is the source of truth for its status; this table is a view of it.",
  "",
  "One file per task is what keeps concurrent branches from colliding (**ADR-015**, extended by ENG-019).",
  "Two branches adding two tasks touch two different files. This index is marked `merge=union` in",
  "`.gitattributes`, so their rows merge automatically; if the result is out of order, run",
  "`npm run tasks:build` rather than resolving it by hand.",
  "",
  "| Task | Status | Branch |",
  "| --- | --- | --- |",
  ...tasks.map((task) => `| [${task.id}](${task.id}.md) ${toCell(task.title, 80)} | ${toCell(task.status, 90)} | ${task.branch ? `\`${task.branch}\`` : "—"} |`),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(INDEX, "utf8");
  } catch {
    console.error(`tasks: ${INDEX} is missing. Run \`npm run tasks:build\`.`);
    process.exit(1);
  }
  if (committed === rendered) {
    console.log(`tasks: OK — ${INDEX} matches ${DIRECTORY}/ (${tasks.length} tasks).`);
    process.exit(0);
  }
  console.error(
    `tasks: ${INDEX} does not match ${DIRECTORY}/.\n` +
      "  The index is generated; the source of truth is each task's **Status:** line in its own file.\n" +
      "  Fix: run `npm run tasks:build` and commit the result. Do not edit the index by hand.",
  );
  process.exit(1);
}

writeFileSync(INDEX, rendered);
console.log(`tasks: wrote ${tasks.length} tasks into ${INDEX}.`);
